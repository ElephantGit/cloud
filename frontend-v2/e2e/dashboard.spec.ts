import { expect, test } from '@playwright/test'
import { signIn } from './login.ts'

test('dashboard analysis reads the real server with mock disabled', async ({ page }) => {
  await page.goto('/dashboard')
  await signIn(page)
  await expect(page.getByRole('heading', { level: 1, name: 'Dashboard' })).toBeVisible()
  await expect(page.getByRole('region', { name: '空间用量', exact: true })).toHaveCount(0)
  const overview = page.getByRole('region', { name: '任务概览', exact: true })
  await expect(overview).toBeVisible()
  const refreshedTasks = page.waitForResponse(response => /\/api\/v2\/tenants\/[^/]+\/tasks$/.test(new URL(response.url()).pathname) && response.request().method() === 'GET')
  await page.getByRole('button', { name: '刷新概览', exact: true }).click()
  const tasks = await (await refreshedTasks).json()
  await expect(page.getByRole('button', { name: '刷新概览', exact: true })).toBeEnabled()
  for (const [label, status] of [['进行中', 'running'], ['待验收', 'review'], ['已完成', 'done']]) {
    const tile = overview.locator('article').filter({ has: page.getByText(label, { exact: true }) })
    await expect(tile.locator('strong')).toHaveText(String(tasks.items.filter((task: { status: string }) => task.status === status).length))
  }
  await page.getByRole('button', { name: '刷新概览', exact: true }).click()
  await expect(page.getByRole('button', { name: '刷新概览', exact: true })).toBeEnabled()
  await page.getByRole('navigation', { name: 'Dashboard 分区' }).getByRole('link', { name: /会话分析/ }).click()
  await expect(page.getByRole('heading', { level: 2, name: '会话分析' })).toBeVisible()
  await expect(page.getByText('正在读取会话…')).not.toBeVisible()
  await expect(page.getByRole('list', { name: 'Agent 会话' })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('dashboard-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: test.info().outputPath('dashboard-mobile.png'), fullPage: true })
  await page.getByLabel('Agent 标识').fill(`absent-${crypto.randomUUID()}`)
  await page.getByRole('button', { name: '应用筛选' }).click()
  await expect(page.getByText('暂无符合条件的会话。')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Agent 标识')).not.toHaveValue('')
  await page.goto('/dashboard/sessions?source=chat')
  await expect(page.getByRole('heading', { level: 1, name: 'Dashboard' })).toBeVisible()
  await expect(page.getByLabel('来源', { exact: true })).toHaveValue('chat')
  await page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: 'Dashboard', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
})

test('ordinary chat appears in dashboard with observed requests and a working return link', async ({ page }) => {
  test.skip(!process.env.V2_NODE_ASSETS_DIR, 'requires real Node/Agent assets')
  test.setTimeout(360_000)
  const title = `普通对话验收-${crypto.randomUUID().slice(0, 8)}`
  await page.goto('/chat')
  await signIn(page)
  await page.getByRole('button', { name: '选择项目' }).click()
  await page.getByRole('option', { name: 'Demo', exact: true }).click()
  await page.getByRole('textbox', { name: '消息' }).fill(title)
  await page.keyboard.press('Enter')
  await expect(page.getByText('V2 fixture complete. Real Agent executed the shell tool.', { exact: true })).toBeVisible({ timeout: 300_000 })
  await page.getByRole('textbox', { name: '消息' }).fill('继续检查并总结。')
  await page.keyboard.press('Enter')
  await expect(page.getByText('V2 fixture complete. Real Agent executed the shell tool.', { exact: true })).toHaveCount(2, { timeout: 300_000 })
  await page.goto('/dashboard/sessions')
  await page.getByLabel('来源', { exact: true }).selectOption('chat')
  await page.getByRole('button', { name: '应用筛选' }).click()
  await expect(page).toHaveURL(/source=chat/)
  await page.reload()
  await expect(page.getByLabel('来源', { exact: true })).toHaveValue('chat')
  await page.getByRole('link', { name: title, exact: true }).click()
  await expect(page.getByRole('region', { name: '会话概览' })).toBeVisible()
  await expect(page.getByText(/来源：普通对话执行时保存的记录/)).toBeVisible()
  await page.getByRole('button', { name: '时间轴', exact: true }).click()
  await expect(page.getByRole('region', { name: '会话时间轴' })).toContainText('Turn 2')
  await expect(page.getByRole('region', { name: '会话时间轴' })).toContainText('继续检查并总结。')
  await page.screenshot({ path: test.info().outputPath('chat-timeline.png'), fullPage: true })
  await page.getByRole('button', { name: '模型请求', exact: true }).click()
  await expect(page.getByRole('region', { name: '模型请求明细' })).toContainText('fixture 测试模型')
  await page.screenshot({ path: test.info().outputPath('chat-requests.png'), fullPage: true })
  await page.getByRole('link', { name: '返回来源' }).click()
  await expect(page.getByRole('heading', { level: 2, name: title })).toBeVisible()
  await expect(page.getByText('V2 fixture complete. Real Agent executed the shell tool.', { exact: true })).toHaveCount(2)
})

test('real Agent task history and model requests appear in dashboard', async ({ page }) => {
  test.skip(!process.env.V2_NODE_ASSETS_DIR, 'requires real Node/Agent assets')
  test.setTimeout(360_000)
  const title = `dashboard Agent-${crypto.randomUUID().slice(0, 8)}`
  await page.goto('/collaboration')
  await signIn(page)
  await page.getByRole('main').getByRole('button', { name: '新建任务' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('任务标题').fill(title)
  await dialog.getByLabel('描述（可选）').fill('读取 README 并检查项目。')
  await expect(dialog.getByLabel('所属项目')).not.toHaveValue('')
  await dialog.getByRole('button', { name: '创建任务' }).click()
  const side = page.getByRole('complementary', { name: '任务属性' })
  await side.getByLabel('指派给').selectOption({ label: 'OpenCode' })
  await side.getByLabel('执行模型').selectOption({ label: 'OpenCode / Fixture' })
  await side.getByRole('button', { name: '开始处理' }).click()
  await expect(
    page.getByRole('region', { name: '运行与讨论' }).getByText(
      'V2 fixture complete. Real Agent executed the shell tool.',
    ),
  ).toBeVisible({ timeout: 300_000 })
  const taskUrl = page.url()
  await page.goto('/dashboard/sessions')
  await page.getByPlaceholder('例如 official/ora-space.opencode').fill('official/ora-space.opencode')
  await page.getByRole('button', { name: '应用筛选' }).click()
  await expect(page).toHaveURL(/agent=official%2Fora-space.opencode/)
  await page.reload()
  await page.getByRole('link', { name: title, exact: true }).click()
  await expect(page.getByRole('region', { name: '会话概览' })).toBeVisible()
  await page.getByRole('button', { name: '时间轴', exact: true }).click()
  await expect(page.getByRole('region', { name: '会话时间轴' })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('dashboard-timeline.png'), fullPage: true })
  await page.getByRole('button', { name: '模型请求', exact: true }).click()
  await expect(page.getByRole('region', { name: '模型请求明细' })).toBeVisible()
  await expect(page.getByRole('region', { name: '模型请求明细' })).toContainText('fixture 测试模型')
  await page.screenshot({ path: test.info().outputPath('dashboard-requests.png'), fullPage: true })
  await page.reload()
  await expect(page.getByRole('heading', { name: title })).toBeVisible()
  await page.getByRole('link', { name: '返回来源' }).click()
  await expect(page).toHaveURL(taskUrl)
})
