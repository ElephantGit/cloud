/// <reference lib="dom" />
import { expect, test } from '@playwright/test'

test('configuration persists through reload, edits, pause and resume', async ({ page }) => {
  const suffix = crypto.randomUUID().slice(0, 8)
  const name = `持久化验收-${suffix}`
  const edited = `${name}-已编辑`
  // An empty list renders a second 新建任务 in its empty state, so always use the page header's.
  const create = page.locator('header').getByRole('button', { name: '新建任务', exact: true })
  await page.goto('/schedules')
  await page.getByRole('button', { name: '开发者登录' }).click()
  await expect(page.getByRole('heading', { name: '定时任务', exact: true })).toBeVisible()
  await create.click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: '任务名称' }).fill(name)
  await dialog.getByRole('textbox', { name: '任务指令' }).fill('整理产品动态')
  await dialog.getByRole('button', { name: '创建并启用' }).click()
  await expect(dialog.getByRole('heading', { name })).toBeVisible()
  await expect(dialog.getByRole('button',{name:'立即运行',exact:true})).toBeDisabled()
  await expect(dialog.getByText(/执行资源尚未就绪或已失效/)).toBeVisible()
  await dialog.getByRole('button', { name: '暂停任务' }).click()
  await expect(dialog.getByText('已暂停', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '编辑' }).click()
  await dialog.getByRole('textbox', { name: '任务名称' }).fill(edited)
  await dialog.getByRole('button', { name: '保存修改' }).click()
  await expect(dialog.getByRole('heading', { name: edited })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: `查看${edited}` })).toBeVisible()
  await page.getByRole('button', { name: `查看${edited}` }).click()
  await expect(dialog.getByText('已暂停', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '恢复任务' }).click()
  await expect(dialog.getByText('已启用', { exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('desktop.png'), fullPage: true })
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await create.click()
  await dialog.getByRole('textbox', { name: '任务名称' }).fill(`移动端-${suffix}`)
  await dialog.getByRole('textbox', { name: '任务指令' }).fill('生成摘要')
  await dialog.getByRole('button', { name: '创建并启用' }).click()
  await expect(dialog.getByRole('heading', { name: `移动端-${suffix}` })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('mobile.png'), fullPage: true })
})
