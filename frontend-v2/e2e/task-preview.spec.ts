/// <reference lib="dom" />
import { expect, test } from '@playwright/test'

test('task preview stays isolated, supports editing, history and narrow screens', async ({ page }) => {
  const writes: string[] = []
  page.on('request', request => { if (request.url().includes('/api/') && request.method() !== 'GET') writes.push(request.url()) })
  await page.goto('/schedules?preview=task')
  await page.getByRole('button', { name: '开发者登录' }).click()
  await page.getByRole('button', { name: '新建定时任务', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('选择任务').fill('142')
  await dialog.getByRole('button', { name: /CLOUD-142/ }).click()
  await dialog.getByLabel('任务名称').fill('定期检查依赖')
  await dialog.getByLabel('补充说明（可选）').fill('输出简洁清单')
  await page.screenshot({ path: test.info().outputPath('task-selection.png'), fullPage: true })
  await page.keyboard.press('Escape')
  await expect(dialog.getByText('放弃未保存的修改？')).toBeVisible()
  await dialog.getByRole('button', { name: '继续编辑' }).click()
  await dialog.getByRole('button', { name: '保存演示配置' }).click()
  await expect(dialog.getByRole('heading', { name: '定期检查依赖' })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('task-config.png'), fullPage: true })
  await dialog.getByRole('button', { name: '暂停', exact: true }).click()
  await dialog.getByRole('button', { name: '恢复', exact: true }).click()
  await dialog.getByRole('button', { name: '模拟运行', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('演示结果')
  await dialog.getByRole('button', { name: '模拟失败', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('演示失败')
  await page.screenshot({ path: test.info().outputPath('task-history.png'), fullPage: true })
  await dialog.getByRole('button', { name: '编辑', exact: true }).click()
  await expect(dialog.getByLabel('任务名称')).toHaveValue('定期检查依赖')
  await expect(dialog.getByLabel('补充说明（可选）')).toHaveValue('输出简洁清单')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(dialog.getByLabel('选择任务')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('task-mobile.png'), fullPage: true })
  expect(writes).toEqual([])
  await page.reload()
  await expect(page.getByRole('button', { name: /定期检查依赖/ })).toHaveCount(0)
})
