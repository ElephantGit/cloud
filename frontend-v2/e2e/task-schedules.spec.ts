/// <reference lib="dom" />
import { expect, test } from '@playwright/test'

test('configures a workflow schedule without calling configuration writes', async ({ page }) => {
  await page.goto('/schedules')
  await page.getByRole('button', { name: '开发者登录' }).click()
  await page.locator('.sp-page-header').getByRole('button', { name: '新建任务' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: /运行工作流/ }).click()
  await dialog.getByLabel('任务名称').fill('演示工作流定时')
  await dialog.getByRole('button', { name: /发布检查.*v3/ }).click()
  await dialog.getByLabel('检查分支 *').fill('main')
  await dialog.getByLabel('关联项目').selectOption('website')
  await dialog.getByRole('button', { name: '创建并启用' }).click()
  await expect(dialog.getByText(/工作流配置为前端演示，刷新后清除/)).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('workflow-config.png'), fullPage: true })
})

test('existing task schedules extend the original table and drawer without API writes', async ({ page }) => {
  const writes: string[] = []
  page.on('request', request => { if (request.url().includes('/api/') && request.method() !== 'GET') writes.push(request.url()) })
  await page.goto('/schedules')
  await page.getByRole('button', { name: '开发者登录' }).click()
  await expect(page.getByLabel('状态筛选')).toBeVisible()
  await expect(page.getByText('体验新功能')).toHaveCount(0)
  await page.locator('.sp-page-header').getByRole('button', { name: '新建任务', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('任务指令')).toBeVisible()
  await dialog.getByRole('button', { name: /已有任务/ }).click()
  await page.screenshot({ path: test.info().outputPath('task-picker.png'), fullPage: true })
  await dialog.getByLabel('选择任务').fill('142')
  await dialog.getByRole('button', { name: /CLOUD-142/ }).click()
  await dialog.getByLabel('任务名称').fill('定期检查依赖')
  await dialog.getByLabel('补充说明（可选）').fill('输出简洁清单')
  await dialog.getByLabel('任务名称').scrollIntoViewIfNeeded()
  await page.screenshot({ path: test.info().outputPath('task-selection.png'), fullPage: true })
  await page.keyboard.press('Escape')
  await expect(dialog.getByText('放弃未保存的修改？')).toBeVisible()
  await dialog.getByRole('button', { name: '继续编辑' }).click()
  await dialog.getByRole('button', { name: '创建并启用' }).click()
  await expect(dialog.getByRole('heading', { name: '定期检查依赖' })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('task-config.png'), fullPage: true })
  await dialog.getByRole('button', { name: '暂停任务', exact: true }).click()
  await dialog.getByRole('button', { name: '恢复任务', exact: true }).click()
  await dialog.getByRole('button', { name: '模拟运行', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('演示结果')
  await dialog.getByText('演示选项', { exact: true }).click()
  await dialog.getByRole('button', { name: '模拟失败', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('演示失败')
  await page.screenshot({ path: test.info().outputPath('task-history.png'), fullPage: true })
  await dialog.getByRole('button', { name: '编辑', exact: true }).click()
  await expect(dialog.getByLabel('任务名称')).toHaveValue('定期检查依赖')
  await expect(dialog.getByLabel('补充说明（可选）')).toHaveValue('输出简洁清单')
  await dialog.getByLabel('任务名称').fill('定期检查依赖（已编辑）')
  await dialog.getByRole('button', { name: '保存修改' }).click()
  await dialog.getByRole('button', { name: '关闭面板' }).click()
  await expect(page.getByRole('columnheader', { name: '最近运行' })).toBeVisible()
  const row = page.getByRole('row').filter({ has: page.getByRole('button', { name: '查看定期检查依赖（已编辑）' }) })
  await row.getByRole('switch').click()
  await expect(row.getByRole('switch')).not.toBeChecked()
  await page.screenshot({ path: test.info().outputPath('task-list-all.png'), fullPage: true })
  await page.getByLabel('执行方式筛选').selectOption('task')
  await expect(row).toBeVisible()
  await page.getByLabel('项目筛选').selectOption('product')
  await expect(row).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('task-list.png'), fullPage: true })
  await row.getByRole('button', { name: '查看定期检查依赖（已编辑）' }).click()
  await dialog.getByRole('button', { name: '编辑', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(dialog.getByRole('button', { name: '更换任务' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('task-mobile.png'), fullPage: true })
  expect(writes).toEqual([])
  await page.reload()
  await expect(page.getByRole('button', { name: /查看定期检查依赖/ })).toHaveCount(0)
})
