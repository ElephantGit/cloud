import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'

test('create, freeze a version, update, reload and archive a workflow', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  const name = `客户反馈整理 ${Date.now()}`
  await page.goto('/workflows')
  await page.getByRole('button', { name: '开发者登录' }).click()
  await page.getByRole('link', { name: '新建工作流' }).click()
  await page.getByRole('textbox', { name: '名称' }).fill(name)
  await page.getByRole('textbox', { name: '描述' }).fill('整理客户输入，保留每次发布的流程版本。')
  await page.getByRole('button', { name: '保存草稿' }).click()
  await expect(page.getByRole('heading', { name })).toBeVisible()
  await expect(page).toHaveURL(/workflow=[a-f0-9-]+/)
  await page.getByRole('button', { name: '发布版本' }).click()
  await expect(page.getByRole('status')).toHaveText('版本 v1 已发布，内容已冻结。')

  await page.getByText('流程 JSON 和导入').click()
  const original = await page.getByRole('textbox', { name: '流程 JSON' }).inputValue()
  const graph = JSON.parse(original)
  graph.nodes[0].data.title = '新的开始'
  graph.annotations = { preserved: [null, false, 0] }
  await page.getByRole('textbox', { name: '流程 JSON' }).fill(JSON.stringify(graph, null, 2))
  await page.getByRole('button', { name: '保存草稿' }).click()
  await expect(page.getByText('草稿已保存。')).toBeVisible()
  await page.reload()
  await page.getByText('流程 JSON 和导入').click()
  await expect(page.getByRole('textbox', { name: '流程 JSON' })).toHaveValue(/新的开始/)
  await page.locator('main').evaluate((element) => { element.scrollTop = 0 })
  await page.screenshot({ path: testInfo.outputPath('workflow-overview.png') })
  await page.getByRole('button', { name: new RegExp('v1.*' + name) }).click()
  await page.getByText('版本 JSON').click()
  await expect(page.getByLabel('版本内容')).not.toContainText('新的开始')
  await expect(page.getByLabel('版本内容')).toContainText('开始')
  await expect(page.getByText('当前支持草稿与版本管理', { exact: false })).toBeVisible()
  await page.getByRole('region', { name: '已发布版本' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('workflow-assets.png'), fullPage: true })

  await page.getByText('工作流信息').click()
  await page.getByRole('textbox', { name: '描述' }).fill('尚未保存')
  await page.getByRole('link', { name: '对话', exact: true }).click()
  await expect(page.getByRole('alertdialog', { name: '未保存的修改' })).toBeVisible()
  await page.getByRole('button', { name: '继续编辑' }).click()
  await expect(page.getByRole('textbox', { name: '描述' })).toHaveValue('尚未保存')
  await page.getByRole('button', { name: '保存草稿' }).click()
  await expect(page.getByText('草稿已保存。')).toBeVisible()
  await page.getByRole('button', { name: '归档工作流', exact: true }).click()
  await page.getByRole('button', { name: '确认归档', exact: true }).click()
  await expect(page.getByRole('heading', { name: '把想法变成可复用的流程' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: '工作流列表' }).getByText(name)).toHaveCount(0)
})


test('imports desktop graph, edits during save, exports, publishes and restores', async ({ page }, testInfo) => {
  const name = `桌面迁移验收 ${Date.now()}`
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/workflows')
  await page.getByRole('button', { name: '开发者登录' }).click()
  await page.getByRole('link', { name: '新建工作流' }).click()
  await page.getByRole('textbox', { name: '名称' }).fill(name)
  await page.getByText('流程 JSON 和导入').click()
  const file = resolve('../v2-server/internal/server/testdata/desktop-workflow.json')
  await page.getByLabel('导入 JSON 文件').setInputFiles(file)
  await expect(page.getByRole('dialog', { name: '导入预览' })).toBeVisible()
  await page.getByRole('dialog', { name: '导入预览' }).screenshot({ path: testInfo.outputPath('import-preview.png') })
  await page.getByRole('button', { name: '确认导入' }).click()
  await expect(page.getByRole('textbox', { name: '流程 JSON' })).toHaveValue(/loopExit/)
  await page.getByRole('button', { name: '变量聚合' , exact: true }).click()
  await page.getByRole('button', { name: '迭代', exact: true }).click()
  const aggregate = page.locator('[data-workflow-node="aggregator-1"]')
  await aggregate.click()
  await page.locator('.workflow-inspector').getByLabel('名称', { exact: true }).fill('聚合验收')
  await page.getByRole('button', { name: '开始 输出 默认', exact: true }).click()
  await page.getByRole('button', { name: '连接到聚合验收' }).click()
  const before = await aggregate.getAttribute('style')
  const bounds = (await aggregate.boundingBox())!
  await page.mouse.move(bounds.x + 60, bounds.y + 20)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 150, bounds.y + 75, { steps: 5 })
  await page.mouse.up()
  await expect(aggregate).not.toHaveAttribute('style', before!)
  await page.locator('.workflow-canvas-shell').screenshot({ path: testInfo.outputPath('node-configuration.png') })
  await page.getByRole('button', { name: 'Agent', exact: true }).click()
  await page.getByRole('button', { name: '删除节点' }).click()
  await expect(page.locator('[data-workflow-node="agent-1"]')).toHaveCount(0)
  await page.getByRole('button', { name: '保存草稿' }).click()
  await expect(page).toHaveURL(/workflow=[a-f0-9-]+/)
  await page.getByRole('button', { name: '发布版本' }).click()
  await expect(page.getByText('版本 v1 已发布，内容已冻结。')).toBeVisible()
  await page.getByRole('button', { name: '整理节点' }).click()
  await page.getByRole('button', { name: '适应画布' }).click()
  await page.getByRole('button', { name: '循环 Agent 输出 默认' }).click()
  await page.getByRole('button', { name: '退出循环', exact: true }).click()
  await expect(page.locator('[data-workflow-node="loopExit-2"]')).toHaveCount(1)
  await page.getByRole('button', { name: '关闭节点详情' }).click()
  await page.getByRole('button', { name: '迭代 输出 iteration-entry' }).click()
  await page.getByRole('button', { name: 'Agent', exact: true }).click()
  await expect(page.locator('[data-workflow-node="agent-1"]')).toHaveCount(1)
  await page.getByRole('button', { name: '折叠迭代' }).click()
  await expect(page.locator('[data-workflow-node="agent-1"]')).toHaveCount(0)
  await page.getByRole('button', { name: '展开迭代' }).click()
  await expect(page.locator('[data-workflow-node="agent-1"]')).toHaveCount(1)
  await page.getByRole('button', { name: '关闭节点详情' }).click()
  await page.getByRole('button', { name: '适应画布' }).click()
  await page.locator('main').evaluate((element) => { element.scrollTop = 0 })
  await page.screenshot({ path: testInfo.outputPath('desktop-import-canvas.png') })
  await expect(page.getByText('草稿已保存。')).toBeVisible()
  let release!: () => void
  const gate = new Promise<void>((resolve) => { release = resolve })
  let first = true
  await page.route('**/api/v1/tenants/*/workflows/*', async (route) => {
    if (route.request().method() === 'PUT' && first) { first = false; const response = await route.fetch(); await gate; await route.fulfill({ response }); return }
    await route.continue()
  })
  await page.getByText('工作流信息').click()
  const description = page.getByPlaceholder('这个工作流帮助你完成什么？')
  await description.fill('第一次保存')
  await page.getByRole('button', { name: '保存草稿' }).click()
  await expect.poll(() => first).toBe(false)
  await description.fill('保存期间继续编辑')
  release()
  await expect(page.getByText('草稿已保存。')).toBeVisible()
  await page.reload()
  await page.getByText('工作流信息').click()
  await expect(description).toHaveValue('保存期间继续编辑')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出', exact: true }).click()
  const download = await downloadPromise
  const exported = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(exported.nodes.map((node: { data: { kind: string } }) => node.data.kind)).toEqual(expect.arrayContaining(['start', 'agent', 'condition', 'aggregator', 'loop', 'loopExit', 'iteration', 'output']))
  expect(exported.nodes.find((node: { id: string }) => node.id === 'loop-1-start').parentId).toBe('loop-1')
  const iteration = exported.nodes.find((node: { id: string }) => node.id === 'iteration-1')
  const member = exported.nodes.find((node: { id: string }) => node.id === 'agent-1')
  expect(iteration.initialWidth).toBeGreaterThanOrEqual(member.position.x + 210)
  expect(iteration.initialHeight).toBeGreaterThanOrEqual(member.position.y + 94)
  expect(exported.edges).toEqual(expect.arrayContaining([expect.objectContaining({ source: 'start', target: 'aggregator-1' }), expect.objectContaining({ source: 'loop-1-agent', target: 'loopExit-2' }), expect.objectContaining({ source: 'iteration-1', sourceHandle: 'iteration-entry', target: 'agent-1' })]))
  await page.getByRole('button', { name: new RegExp('v1.*' + name) }).click()
  await page.getByRole('button', { name: '恢复为草稿' }).click()
  await page.getByRole('button', { name: '确认恢复' }).click()
  await expect(page.getByText('历史版本已恢复为草稿。')).toBeVisible()
  const versions = page.getByRole('region', { name: '已发布版本' })
  await versions.getByRole('button', { name: '适应画布' }).click()
  await versions.screenshot({ path: testInfo.outputPath('restored-version.png') })
})
