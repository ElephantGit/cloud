import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/schedules?variant=A')
  await page.getByRole('button', { name: '开发者登录' }).click()
  await expect(page.getByRole('heading', { name: '定时任务', exact: true })).toBeVisible()
})

test('create independent chat, pause, simulate failure, retry, edit and delete without API mutations', async ({ page }) => {
  const writes: string[] = []
  page.on('request', request => { if (/\/api\//.test(request.url()) && !['GET', 'HEAD'].includes(request.method())) writes.push(request.url()) })
  const create = page.getByRole('button', { name: '新建任务', exact: true })
  await create.click()
  await expect(page.getByRole('textbox', { name: '任务名称' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(create).toBeFocused()
  await create.click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: '任务名称' }).fill('独立对话验收')
  await dialog.getByRole('textbox', { name: '任务指令' }).fill('整理当天产品动态。')
  await dialog.getByRole('button', { name: '创建并启用' }).click()
  await expect(dialog.getByRole('heading', { name: '独立对话验收' })).toBeVisible()
  await dialog.getByRole('button', { name: '暂停任务', exact: true }).click()
  await dialog.getByRole('tab', { name: /运行记录/ }).click()
  await dialog.getByText('演示选项', { exact: true }).click()
  await dialog.getByRole('button', { name: '模拟一次失败' }).click()
  await expect(dialog.getByText('运行中', { exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: '重新模拟' })).toBeVisible()
  await dialog.getByRole('button', { name: '重新模拟' }).click()
  await expect(dialog.getByText('成功', { exact: true })).toBeVisible()
  await expect(dialog.getByText('失败', { exact: true })).toBeVisible()
  await expect(dialog.getByText('已暂停', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '编辑', exact: true }).click()
  await dialog.getByRole('textbox', { name: '任务名称' }).fill('已编辑对话')
  await dialog.getByRole('button', { name: '保存修改' }).click()
  await expect(dialog.getByRole('heading', { name: '已编辑对话' })).toBeVisible()
  await dialog.getByRole('button', { name: '删除任务', exact: true }).click()
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /查看已编辑对话/ })).toHaveCount(0)
  expect(writes).toEqual([])
})

test('workflow validation, fixed version and mobile drawer', async ({ page }) => {
  await page.getByRole('button', { name: '新建任务', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: '任务名称' }).fill('工作流验收')
  await dialog.getByRole('button', { name: /运行工作流/ }).click()
  await expect(dialog.getByRole('button', { name: /竞品观察/ })).toBeDisabled()
  await dialog.getByRole('button', { name: /发布检查/ }).click()
  await dialog.getByRole('button', { name: '创建并启用' }).click()
  await expect(dialog.getByText('运行工作流需要项目，请选择运行环境')).toBeVisible()
  await expect(dialog.getByText('请填写检查分支')).toBeVisible()
  await dialog.getByRole('textbox', { name: /检查分支/ }).fill('main')
  await expect(dialog.getByText('请填写检查分支')).toHaveCount(0)
  await expect(dialog.getByText('运行工作流需要项目，请选择运行环境')).toBeVisible()
  await dialog.getByRole('combobox', { name: '关联项目' }).selectOption('website')
  await dialog.getByRole('button', { name: '创建并启用' }).click()
  await expect(dialog.getByText('v3 · 固定版本')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: '定时任务', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.evaluate(() => innerWidth)).toBe(390)
  const table = page.locator('[data-slot="table-container"]')
  expect(await table.evaluate(el => { el.scrollLeft = el.scrollWidth; return el.scrollLeft > 0 })).toBe(true)
  await table.evaluate(el => { el.scrollLeft = 0 })
  await page.screenshot({ path: test.info().outputPath('mobile.png'), fullPage: true })
  await page.getByRole('button', { name: '新建任务', exact: true }).click()
  await dialog.getByRole('textbox', { name: '任务名称' }).fill('移动端向导')
  await dialog.getByRole('textbox', { name: '任务指令' }).fill('生成简报')
  await dialog.getByRole('button', { name: '创建并启用' }).click()
  await expect(dialog.getByRole('heading', { name: '移动端向导' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.reload()
  await expect(page.getByRole('button', { name: '移动端向导', exact: true })).toHaveCount(0)
})
